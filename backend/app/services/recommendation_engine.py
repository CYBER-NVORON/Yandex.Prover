from __future__ import annotations

from app.schemas import Claim, ImprovementPlan, Recommendation, Weakness


def build_weaknesses(claims: list[Claim], material_type: str, audience_type: str = "") -> list[Weakness]:
    is_teacher = "учитель" in audience_type.lower()
    broad_claim_audience = (
        "Слишком сильные выводы создают точку атаки на защите исследовательской работы."
        if is_teacher
        else "Слишком сильные выводы создают точку атаки для комиссии, жюри или инвестора."
    )
    weaknesses = [
        Weakness(
            problem="Часть ключевых утверждений не подтверждается внутри материала.",
            why_problem="Аудитория может согласиться с проблемой, но не принять вывод без данных, примера или методики.",
            audience_signal="Вопросы будут начинаться с формулировок: 'откуда это известно?' и 'на чём основан вывод?'.",
            fix="Добавить к самым сильным утверждениям источник, расчёт, пример из текста или честное ограничение.",
        ),
        Weakness(
            problem="Недостаточно явно показана связь между проблемой, аргументами и выводом.",
            why_problem="Даже сильная идея теряет убедительность, если переходы между частями выглядят скачками.",
            audience_signal="Слушатель может понять отдельные тезисы, но не увидеть, почему из них следует итоговый вывод.",
            fix="Добавить короткие связки после каждого аргумента: что он доказывает и как приближает к главной мысли.",
        ),
        Weakness(
            problem="Есть формулировки, которые звучат шире, чем позволяет сам материал.",
            why_problem=broad_claim_audience,
            audience_signal="Аудитория может попросить уточнить масштаб, выборку, условия или исключения.",
            fix="Заменить абсолютные формулировки на точные: где, для кого и при каких условиях тезис верен.",
        ),
    ]

    if is_teacher:
        weaknesses.append(
            Weakness(
                problem="Практическая часть и вывод могут быть связаны явнее.",
                why_problem="Учитель на защите исследовательской работы будет смотреть, как наблюдения и источники приводят к выводу.",
                audience_signal="Вопрос может звучать так: 'какая часть работы подтверждает этот вывод?'.",
                fix="После практической части добавить короткую связку: что именно она показывает и какой вывод поддерживает.",
            )
        )
    elif "питч" in material_type.lower():
        weaknesses.append(
            Weakness(
                problem="Бизнес-ценность и отличие от альтернатив описаны недостаточно конкретно.",
                why_problem="Для питча важно показать, почему решение нужно именно сейчас и чем оно лучше привычного способа.",
                audience_signal="Инвестор или жюри спросит про конкурентов, метрики спроса и экономический эффект.",
                fix="Добавить 2-3 конкурента, критерии сравнения и одну проверяемую метрику ценности.",
            )
        )
    else:
        weaknesses.append(
            Weakness(
                problem="Не хватает одного сильного примера, который делает идею проверяемой.",
                why_problem="Без примера материал может восприниматься как общий тезис, а не как доказанное рассуждение.",
                audience_signal="Аудитория попросит привести конкретный случай или показать, как тезис работает на практике.",
                fix="Добавить пример в самую слабую часть и явно объяснить, какой аргумент он усиливает.",
            )
        )

    if any(claim.risk_level == "high" for claim in claims):
        weaknesses.append(
            Weakness(
                problem="Высокорисковые утверждения стоят близко к центральной идее.",
                why_problem="Если аудитория оспорит такой тезис, под удар попадёт не деталь, а вся линия защиты.",
                audience_signal="Самые острые вопросы будут направлены не на стиль, а на основание идеи.",
                fix="Перед защитой подготовить доказательство или смягчить формулировку центрального тезиса.",
            )
        )

    return weaknesses[:5]


def build_recommendations(
    claims: list[Claim],
    weaknesses: list[Weakness],
    audience_knowledge_level: int = 3,
) -> list[Recommendation]:
    if audience_knowledge_level <= 2:
        audience_problem = "Сложные термины и контекст могут быть непонятны неподготовленной аудитории."
        audience_action = "При первом упоминании 2-3 ключевых терминов добавить короткое объяснение и простой пример."
        audience_effect = "Аудитория быстрее поймёт смысл работы и будет задавать вопросы по сути, а не по терминологии."
    elif audience_knowledge_level >= 4:
        audience_problem = "Подготовленная аудитория будет строже проверять метод, ограничения и точность формулировок."
        audience_action = "Добавить короткое обоснование метода, границы вывода и альтернативное объяснение, которое вы учитывали."
        audience_effect = "Материал станет устойчивее к экспертным вопросам без переписывания основной идеи."
    else:
        audience_problem = "Не все термины и критерии оценки очевидны выбранной аудитории."
        audience_action = "Перед первым сложным термином добавить короткое определение и указать, почему этот критерий важен."
        audience_effect = "Снизится риск уточняющих вопросов, не связанных с сутью идеи."

    recommendations = [
        Recommendation(
            id="rec_1",
            priority="high",
            category="Доказательность",
            problem="Есть утверждения, для которых нужен источник или подтверждение внутри материала.",
            action="Отметить 3-5 самых важных утверждений и рядом добавить данные, пример, расчёт или ограничение формулировки.",
            expected_effect="Снизится риск вопросов о неподтверждённых тезисах.",
        ),
        Recommendation(
            id="rec_2",
            priority="high",
            category="Структура",
            problem="Главная мысль может потеряться между проблемой, аргументами и выводом.",
            action="В начале явно сформулировать один главный тезис, а в конце каждого раздела показать, как он подтверждается.",
            expected_effect="Аудитория быстрее поймёт, что именно автор защищает.",
        ),
        Recommendation(
            id="rec_3",
            priority="medium",
            category="Аргументация",
            problem="Некоторые аргументы звучат как мнение.",
            action="Добавить один проверяемый пример к самому слабому аргументу и объяснить, почему этот пример репрезентативен.",
            expected_effect="Материал будет восприниматься как обоснованная позиция, а не набор утверждений.",
        ),
        Recommendation(
            id="rec_4",
            priority="medium",
            category="Аудитория",
            problem=audience_problem,
            action=audience_action,
            expected_effect=audience_effect,
        ),
        Recommendation(
            id="rec_5",
            priority="medium",
            category="Подготовка к вопросам",
            problem="Острые вопросы пока не закрыты в самом материале.",
            action="Вставить отдельный блок 'ограничения и ответы на возможные вопросы' перед выводом или финальным слайдом.",
            expected_effect="Автор будет выглядеть готовым к предзащите и критике.",
        ),
    ]

    high_risk_claims = [claim for claim in claims if claim.risk_level == "high"]
    if high_risk_claims:
        claim = high_risk_claims[0]
        recommendations.insert(
            0,
            Recommendation(
                id="rec_claim_high",
                priority="high",
                category="Рискованное утверждение",
                problem=f"Тезис '{claim.text}' может стать главной точкой атаки.",
                action=claim.recommendation,
                expected_effect="Самый уязвимый фрагмент станет честнее и устойчивее к вопросам.",
            ),
        )

    if weaknesses:
        weakness = weaknesses[0]
        recommendations.append(
            Recommendation(
                id="rec_weakness",
                priority="low",
                category="Редактура",
                problem=weakness.problem,
                action=weakness.fix,
                expected_effect="Материал станет более цельным без переписывания основной идеи.",
            )
        )

    return recommendations[:7]


def build_improvement_plan(recommendations: list[Recommendation], claims: list[Claim]) -> ImprovementPlan:
    risky_claims = [claim.text for claim in claims if claim.risk_level in {"high", "medium"}][:3]
    quick = [
        "Выделить одним предложением главную мысль и поставить её в начало материала.",
        "Смягчить абсолютные формулировки: заменить 'все', 'всегда', 'доказано', 'решает проблему' на точные условия.",
        "Подписать у рискованных тезисов пометки: 'нужен источник' или 'подтвердить примером'.",
    ]
    if risky_claims:
        quick.append(f"Проверить формулировку: {risky_claims[0]}")

    two_hours = [
        "Добавить доказательство к каждому высокорисковому утверждению: источник, расчёт, кейс или фрагмент методики.",
        "Перестроить середину материала по схеме: проблема -> аргумент -> доказательство -> вывод для аудитории.",
        "Добавить сравнение с альтернативами по 2-3 понятным критериям.",
    ]

    polish = [
        "Сделать финальный проход по вопросам аудитории и добавить ответы на самые опасные из них в материал.",
        "Убрать повторения, оставить только тезисы, которые работают на главную мысль.",
        "Проверить, что вывод не шире доказательств, которые есть в тексте.",
    ]

    if recommendations:
        two_hours.insert(0, recommendations[0].action)

    return ImprovementPlan(
        quick_fixes_30_min=quick[:4],
        improvements_2_hours=two_hours[:4],
        final_polish=polish[:4],
    )

